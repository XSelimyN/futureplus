/**
 * Skybox drawing. Called in the vanilla sky pass (instead of SkyRenderer.renderSkyDisc).
 *
 * <h2>Cache (default, in shader mode)</h2>
 * The sky is NOT recomputed across the screen every frame. Instead it is "baked" into an
 * equirectangular texture (4096x2048) by world directions, and each frame only reads from that texture (as cheap as texture mode).
 *
 *  - Baking is done piece by piece: a few row bands per frame. ~20 full refreshes per second (adjustable),
 *    so the shader work per second is FIXED whatever the FPS -> at 400 FPS about ~15% of the screen's worth of work per frame.
 *  - Three textures rotate (previous / shown / baking). The shown image fades smoothly between two finished frames,
 *    so a half baked texture is never seen, there's no tearing/seam, and motion stays smooth.
 *  - Turning the camera recomputes nothing (the texture is fixed to the world).
 *
 * <h2>Other paths</h2>
 *  - Texture mode : a ready texture generated by SkyTextures (core/futureplus_sky_tex)
 *  - Solid color  : a single color (core/futureplus_sky_fx_plain)
 *  - Cache off / not working: direct drawing (core/futureplus_sky_fx_N), at a lower resolution if wanted (core/futureplus_sky_up)
 *
 * Parameters are sent with the TextureMat inside DynamicTransforms:
 *  column 0 = (time, design, mode, family), column 1 = color, column 2 = size/fade, column 3 = bake band.
 */
public final class SkyRender {
    private SkyRender() {}

    private static final int TEX_W = 4096, TEX_H = 2048;

    // ------------------------------------------------------------- pipelines

    private static final RenderPipeline[] FX = new RenderPipeline[16];   // direct drawing, per design (15 = solid color)
    private static final RenderPipeline[] BAKE = new RenderPipeline[16]; // baking into the cache, per design
    static {
        for (int i = 0; i < 16; i++) {
            String n = i == 15 ? "plain" : String.valueOf(i);
            FX[i] = RenderPipelines.register(
                RenderPipeline.builder(RenderPipelines.MATRICES_PROJECTION_SNIPPET)
                    .withLocation("pipeline/futureplus_sky_fx_" + n)
                    .withVertexShader("core/futureplus_sky")
                    .withFragmentShader("core/futureplus_sky_fx_" + n)
                    .withVertexFormat(DefaultVertexFormat.POSITION, VertexFormat.Mode.QUADS)
                    .withCull(false)
                    .build());
            BAKE[i] = RenderPipelines.register(
                RenderPipeline.builder(RenderPipelines.MATRICES_PROJECTION_SNIPPET)
                    .withLocation("pipeline/futureplus_sky_bake_" + n)
                    .withVertexShader("core/futureplus_sky_bake")
                    .withFragmentShader("core/futureplus_sky_bake_" + n)
                    .withVertexFormat(DefaultVertexFormat.POSITION, VertexFormat.Mode.QUADS)
                    .withCull(false)
                    .build());
        }
    }

    public static final RenderPipeline SHOW = RenderPipelines.register(
        RenderPipeline.builder(RenderPipelines.MATRICES_PROJECTION_SNIPPET)
            .withLocation("pipeline/futureplus_sky_show")
            .withVertexShader("core/futureplus_sky")
            .withFragmentShader("core/futureplus_sky_show")
            .withSampler("Sampler0")
            .withSampler("Sampler1")
            .withVertexFormat(DefaultVertexFormat.POSITION, VertexFormat.Mode.QUADS)
            .withCull(false)
            .build());

    public static final RenderPipeline TEX = RenderPipelines.register(
        RenderPipeline.builder(RenderPipelines.MATRICES_PROJECTION_SNIPPET)
            .withLocation("pipeline/futureplus_sky_tex")
            .withVertexShader("core/futureplus_sky")
            .withFragmentShader("core/futureplus_sky_tex")
            .withSampler("Sampler0")
            .withVertexFormat(DefaultVertexFormat.POSITION, VertexFormat.Mode.QUADS)
            .withCull(false)
            .build());

    public static final RenderPipeline UP = RenderPipelines.register(
        RenderPipeline.builder(RenderPipelines.MATRICES_PROJECTION_SNIPPET)
            .withLocation("pipeline/futureplus_sky_up")
            .withVertexShader("core/futureplus_sky")
            .withFragmentShader("core/futureplus_sky_up")
            .withSampler("Sampler0")
            .withVertexFormat(DefaultVertexFormat.POSITION, VertexFormat.Mode.QUADS)
            .withCull(false)
            .build());

    /** Loads the class early (so pipelines register before resource loading). */
    static void init() { }

    // ------------------------------------------------------------- geometri

    private static GpuBuffer cube, quad;

    private static GpuBuffer cube() {
        if (cube != null) return cube;
        VertexFormat fmt = DefaultVertexFormat.POSITION;
        try (ByteBufferBuilder bb = ByteBufferBuilder.exactlySized(24 * fmt.getVertexSize())) {
            BufferBuilder b = new BufferBuilder(bb, VertexFormat.Mode.QUADS, fmt);
            float s = 100f;
            // +X, -X, +Y, -Y, +Z, -Z faces (seen from the inside; cull off)
            quad(b, s, -s, -s, s, s, -s, s, s, s, s, -s, s);
            quad(b, -s, -s, s, -s, s, s, -s, s, -s, -s, -s, -s);
            quad(b, -s, s, -s, -s, s, s, s, s, s, s, s, -s);
            quad(b, -s, -s, s, -s, -s, -s, s, -s, -s, s, -s, s);
            quad(b, s, -s, s, s, s, s, -s, s, s, -s, -s, s);
            quad(b, -s, -s, -s, -s, s, -s, s, s, -s, s, -s, -s);
            try (MeshData mesh = b.buildOrThrow()) {
                cube = RenderSystem.getDevice().createBuffer(() -> "Futureplus sky cube", 32, mesh.vertexBuffer());
            }
        }
        return cube;
    }

    /** Full screen quad (-1..1) for baking; the vertex shader squeezes it into the band range. */
    private static GpuBuffer quadBuf() {
        if (quad != null) return quad;
        VertexFormat fmt = DefaultVertexFormat.POSITION;
        try (ByteBufferBuilder bb = ByteBufferBuilder.exactlySized(4 * fmt.getVertexSize())) {
            BufferBuilder b = new BufferBuilder(bb, VertexFormat.Mode.QUADS, fmt);
            quad(b, -1, -1, 0, 1, -1, 0, 1, 1, 0, -1, 1, 0);
            try (MeshData mesh = b.buildOrThrow()) {
                quad = RenderSystem.getDevice().createBuffer(() -> "Futureplus sky quad", 32, mesh.vertexBuffer());
            }
        }
        return quad;
    }

    private static void quad(BufferBuilder b, float... v) {
        for (int i = 0; i < 12; i += 3) b.addVertex(v[i], v[i + 1], v[i + 2]);
    }

    // ------------------------------------------------------------- main entry

    private static double shaderTime = 0;
    private static long lastNs = 0;

    /** Called instead of the vanilla sky (render thread). */
    public static void render() {
        long now = System.nanoTime();
        float dt = lastNs == 0 ? 0f : (float) Math.min(0.1, (now - lastNs) / 1e9);
        lastNs = now;
        shaderTime += dt * Skybox.speed;

        int mode = Skybox.mode;
        int col = mode == 2 ? Skybox.shaderColor : (mode == 0 ? 0x05060A : Skybox.color);
        float r = ((col >> 16) & 255) / 255f, g = ((col >> 8) & 255) / 255f, bl = (col & 255) / 255f;
        float time = (float) (shaderTime % 3600.0);

        RenderTarget main = Minecraft.getInstance().getMainRenderTarget();
        GpuTextureView color = main.getColorTextureView();
        GpuTextureView depth = main.getDepthTextureView();

        // Texture mode: the ready texture (a dark solid color if not ready)
        if (mode == 0) {
            if (ensureTexture()) {
                draw(TEX, params(time, Skybox.design, 0, r, g, bl, 0, 0, 0, 0, 0, 0), color, depth, cube(), 36,
                    pass -> pass.bindTexture("Sampler0", tex.getTextureView(), tex.getSampler()));
            } else {
                draw(FX[15], params(time, -1, 0, r, g, bl, 0, 0, 0, 0, 0, 0), color, depth, cube(), 36, null);
            }
            return;
        }
        // Solid color: free anyway
        if (mode == 1) {
            draw(FX[15], params(time, -1, 1, r, g, bl, 0, 0, 0, 0, 0, 0), color, depth, cube(), 36, null);
            return;
        }

        int design = Math.max(0, Math.min(14, Skybox.shader));

        // Shader mode, cached (default)
        if (Skybox.cache && !cacheFailed) {
            try {
                if (cachedRender(design, time, dt, r, g, bl, color, depth)) { cacheErrors = 0; return; }
            } catch (Throwable t) {
                // A single error (e.g. another render pass left open at that moment while joining a server) turned the cache off for the
                // whole session and fell back to expensive direct drawing every frame. Turn it off only if it happens several times in a row.
                freeCache();
                if (++cacheErrors >= 5) {
                    cacheFailed = true;
                    System.err.println("[Futureplus] Gokyuzu onbellegi calismadi, dogrudan cizime geciliyor: " + t);
                }
            }
        }

        // Shader mode, direct (cache off) — at a lower resolution if wanted
        float sc = Skybox.resScale();
        if (sc < 0.999f && !lowFailed) {
            int w = Math.max(16, Math.round(main.width * sc)), h = Math.max(16, Math.round(main.height * sc));
            try {
                if (ensureLow(w, h)) {
                    GpuTextureView lowDepth = low.getDepthTextureView();
                    GpuSampler smp = sampler().getSampler();   // before the pass opens: uploads the texture on the first call
                    drawClear(FX[design], params(time, design, 2, r, g, bl, 0, 0, 0, 0, 0, 0), low.getColorTextureView(),
                        lowDepth, cube(), 36, null);
                    draw(UP, params(time, design, 2, r, g, bl, w / (float) main.width, h / (float) main.height, w, h, 0, 0),
                        color, depth, cube(), 36,
                        pass -> pass.bindTexture("Sampler0", low.getColorTextureView(), smp));
                    return;
                }
            } catch (Throwable t) {
                lowFailed = true;
                System.err.println("[Futureplus] Dusuk cozunurluklu gokyuzu calismadi, %100 kullaniliyor: " + t);
            }
        }
        draw(FX[design], params(time, design, 2, r, g, bl, 0, 0, 0, 0, 0, 0), color, depth, cube(), 36, null);
    }

    // ------------------------------------------------------------- cache

    private static final RenderTarget[] buf = new RenderTarget[3];
    private static int cacheW = 0, cacheH = 0;
    private static int iPrev = 0, iFront = 0, iBack = 1;   // previous / shown / baking
    private static int rowsDone = 0;                       // rows done in the baking texture
    private static float rowDebt = 0;                      // fractional row accumulation
    private static float cycleTime = 0;                    // time of the frame being baked (all bands the same moment)
    private static int cycleDesign = -1, cycleColor = 0;
    private static boolean cacheFailed = false;
    private static int cacheErrors = 0;                    // consecutive cache errors
    private static long lastForced = 0;

    private static boolean cachedRender(int design, float time, float dt, float r, float g, float b,
                                        GpuTextureView color, GpuTextureView depth) throws Exception {
        int W = Skybox.cacheWidth(), H = W / 2;
        int colKey = Skybox.shaderColor;

        if (W != cacheW || buf[0] == null) {
            // first open / resolution changed: bake all of it once
            freeCache();
            buf[0] = newTarget(W, H, false);
            buf[1] = newTarget(W, H, false);
            cacheW = W; cacheH = H;
            iPrev = 0; iFront = 0; iBack = 1;
            bake(buf[0], design, time, r, g, b, 0, H, true);
            rowsDone = 0; rowDebt = 0;
            cycleTime = time; cycleDesign = design; cycleColor = colKey;
        }

        // If a setting changed (design/color): bake the new frame fully RIGHT AWAY and show it without a fade (so dragging
        // on the color wheel shows instantly). Not every frame while dragging, at most once per 20 ms.
        if ((design != cycleDesign || colKey != cycleColor) && System.nanoTime() - lastForced > 20_000_000L) {
            lastForced = System.nanoTime();
            bake(buf[iBack], design, time, r, g, b, 0, H, false);
            iFront = iBack;
            iPrev = iBack;
            iBack = iBack == 0 ? 1 : 0;
            if (buf[iBack] == null) buf[iBack] = newTarget(cacheW, cacheH, false);
            rowsDone = 0; rowDebt = 0;
            cycleTime = time; cycleDesign = design; cycleColor = colKey;
        }

        // This frame's bake share: "hz" full refreshes per second (independent of FPS), at most 1/6 of the texture per frame
        rowDebt += H * Skybox.cacheHz * dt;
        int rows = Math.min((int) rowDebt, Math.max(8, H / 6));
        rowDebt -= rows;
        if (rowDebt > H) rowDebt = H;
        if (rows > 0) {
            int r1 = Math.min(H, rowsDone + rows);
            bake(buf[iBack], cycleDesign, cycleTime, r, g, b, rowsDone, r1, false);
            rowsDone = r1;
            if (rowsDone >= H) {
                // frame done: rotate (previous <- shown <- baking <- spare)
                int freeIdx = 3 - iFront - iBack;              // the one of 0, 1, 2 that isn't either of the two
                if (iPrev == iFront) freeIdx = 3 - iFront - iBack;
                iPrev = iFront;
                iFront = iBack;
                if (buf[freeIdx] == null) buf[freeIdx] = newTarget(cacheW, cacheH, false);
                iBack = freeIdx;
                rowsDone = 0;
                cycleTime = time;
            }
        }

        // Show: fade between previous and shown by the bake progress (smooth motion, no tearing)
        float k = rowsDone / (float) cacheH;
        GpuTextureView prevView = buf[iPrev].getColorTextureView(), frontView = buf[iFront].getColorTextureView();
        // The sampler must be taken BEFORE the pass opens: the first call sets up the DynamicTexture and uploads it (writeToTexture);
        // inside an open pass that threw "Close the existing render pass" and turned the cache off every session.
        GpuSampler smp = sampler().getSampler();
        draw(SHOW, params(time, design, 2, r, g, b, k, 0, cacheW, cacheH, 0, 0), color, depth, cube(), 36, pass -> {
            pass.bindTexture("Sampler0", prevView, smp);
            pass.bindTexture("Sampler1", frontView, smp);
        });
        return true;
    }

    /** Bakes rows [r0, r1) of the texture (row 0 = top). */
    private static void bake(RenderTarget t, int design, float time, float r, float g, float b, int r0, int r1, boolean clear) {
        float H = cacheH;
        float y0 = -1f + 2f * r0 / H, y1 = -1f + 2f * r1 / H;
        GpuBufferSlice p = params(time, design, 2, r, g, b, 0, 0, cacheW, cacheH, y0, y1);
        RenderSystem.AutoStorageIndexBuffer quads = RenderSystem.getSequentialBuffer(VertexFormat.Mode.QUADS);
        GpuBuffer index = quads.getBuffer(6);
        GpuBuffer vb = quadBuf();                                   // set up the buffer outside the pass too
        try (RenderPass pass = RenderSystem.getDevice().createCommandEncoder().createRenderPass(
                () -> "Futureplus sky bake", t.getColorTextureView(),
                clear ? OptionalInt.of(0xFF000000) : OptionalInt.empty(), null, OptionalDouble.empty())) {
            pass.setPipeline(BAKE[design]);
            RenderSystem.bindDefaultUniforms(pass);
            pass.setUniform("DynamicTransforms", p);
            pass.setVertexBuffer(0, vb);
            pass.setIndexBuffer(index, quads.type());
            pass.drawIndexed(0, 0, 6, 1);
        }
    }

    private static void freeCache() {
        for (int i = 0; i < 3; i++) {
            if (buf[i] != null) destroy(buf[i]);
            buf[i] = null;
        }
        cacheW = cacheH = 0;
    }

    // ------------------------------------------------------------- shared drawing

    // TextureMat: column 0 = (time, design, mode, family), column 1 = color, column 2 = (a, b, width, height), column 3 = (y0, y1, 0, 1)
    private static GpuBufferSlice params(float time, float design, int mode, float r, float g, float b,
                                         float a, float bb, float w, float h, float y0, float y1) {
        Matrix4f m = new Matrix4f(
            time, design, mode, Skybox.family,
            r, g, b, 1f,
            a, bb, w, h,
            y0, y1, 0f, 1f);
        return RenderSystem.getDynamicUniforms().writeTransform(
            RenderSystem.getModelViewMatrix(), new Vector4f(1f, 1f, 1f, 1f), new Vector3f(), m);
    }

    private static void draw(RenderPipeline pipe, GpuBufferSlice dynamic, GpuTextureView color, GpuTextureView depth,
                             GpuBuffer vb, int indices, Consumer<RenderPass> bind) {
        pass(pipe, dynamic, color, depth, OptionalInt.empty(), OptionalDouble.empty(), vb, indices, bind);
    }

    private static void drawClear(RenderPipeline pipe, GpuBufferSlice dynamic, GpuTextureView color, GpuTextureView depth,
                                  GpuBuffer vb, int indices, Consumer<RenderPass> bind) {
        pass(pipe, dynamic, color, depth, OptionalInt.of(0xFF000000),
            depth != null ? OptionalDouble.of(1.0) : OptionalDouble.empty(), vb, indices, bind);
    }

    private static void pass(RenderPipeline pipe, GpuBufferSlice dynamic, GpuTextureView color, GpuTextureView depth,
                             OptionalInt clearColor, OptionalDouble clearDepth, GpuBuffer vb, int indices,
                             Consumer<RenderPass> bind) {
        RenderSystem.AutoStorageIndexBuffer quads = RenderSystem.getSequentialBuffer(VertexFormat.Mode.QUADS);
        GpuBuffer index = quads.getBuffer(indices);
        try (RenderPass pass = RenderSystem.getDevice().createCommandEncoder().createRenderPass(
                () -> "Futureplus sky", color, clearColor, depth, clearDepth)) {
            pass.setPipeline(pipe);
            RenderSystem.bindDefaultUniforms(pass);
            pass.setUniform("DynamicTransforms", dynamic);
            if (bind != null) bind.accept(pass);
            pass.setVertexBuffer(0, vb);
            pass.setIndexBuffer(index, quads.type());
            pass.drawIndexed(0, 0, indices, 1);
        }
    }

    // ------------------------------------------------------------- render hedefleri

    private static RenderTarget low;
    private static int lowW, lowH;
    private static boolean lowFailed = false;
    private static DynamicTexture samplerTex;           // we only use its sampler (the shaders read with texelFetch)

    private static DynamicTexture sampler() {
        if (samplerTex == null) samplerTex = new DynamicTexture(() -> "futureplus sky sampler", new NativeImage(1, 1, false));
        return samplerTex;
    }

    private static boolean ensureLow(int w, int h) throws Exception {
        if (low != null && lowW == w && lowH == h) return true;
        if (low != null) { destroy(low); low = null; }
        low = newTarget(w, h, true);
        lowW = w; lowH = h;
        return true;
    }

    private static void destroy(RenderTarget t) {
        try { t.getClass().getMethod("destroyBuffers").invoke(t); } catch (Throwable ignored) { }
    }

    /** Sets up a TextureTarget independent of version (constructor parameters: name, width, height, depth ...). */
    private static RenderTarget newTarget(int w, int h, boolean useDepth) throws Exception {
        Class<?> cls = Class.forName("com.mojang.blaze3d.pipeline.TextureTarget");
        for (Constructor<?> c : cls.getConstructors()) {
            Class<?>[] pt = c.getParameterTypes();
            Object[] args = new Object[pt.length];
            int ints = 0, bools = 0;
            boolean ok = true;
            for (int i = 0; i < pt.length; i++) {
                if (pt[i] == String.class) args[i] = "Futureplus sky";
                else if (pt[i] == int.class) { if (ints > 1) { ok = false; break; } args[i] = ints++ == 0 ? w : h; }
                else if (pt[i] == boolean.class) args[i] = bools++ == 0 && useDepth;   // first boolean: depth buffer
                else { ok = false; break; }
            }
            if (!ok || ints != 2) continue;
            return (RenderTarget) c.newInstance(args);
        }
        throw new IllegalStateException("TextureTarget kurucusu bulunamadi");
    }

    // ------------------------------------------------------------- texture modu

    private static Identifier texId;
    private static DynamicTexture tex;
    private static int texKey = -1;                 // ready texture: family*100 + design
    private static int pendingKey = -1;
    private static CompletableFuture<int[]> pending;

    /** True if the selected texture is ready; otherwise starts generating it in the background. */
    private static boolean ensureTexture() {
        int key = Skybox.family * 100 + Skybox.design;
        if (pending != null && pending.isDone()) {
            try {
                int[] px = pending.get();
                upload(px);
                texKey = pendingKey;
            } catch (Throwable t) {
                System.err.println("[Futureplus] Skybox dokusu uretilemedi: " + t);
                texKey = -2;
            }
            pending = null;
        }
        if (texKey == key && tex != null) return true;
        if (pending == null && texKey != key) {
            final int fam = Skybox.family, des = Skybox.design;
            pendingKey = key;
            pending = CompletableFuture.supplyAsync(() -> SkyTextures.generate(fam, des, TEX_W, TEX_H));
        }
        return tex != null && texKey >= 0;              // show the old one until the new one arrives
    }

    private static void upload(int[] px) {
        NativeImage img = new NativeImage(TEX_W, TEX_H, false);
        for (int y = 0; y < TEX_H; y++) {
            int o = y * TEX_W;
            for (int x = 0; x < TEX_W; x++) img.setPixel(x, y, px[o + x]);
        }
        Identifier old = texId;
        texId = Identifier.fromNamespaceAndPath("futureplus", "skybox/" + System.nanoTime());
        tex = new DynamicTexture(() -> "futureplus skybox", img);
        Minecraft.getInstance().getTextureManager().register(texId, tex);
        if (old != null) Minecraft.getInstance().getTextureManager().release(old);
    }
}
